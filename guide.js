  GUIDE_PAGES.forEach(function(cap, i){
    var n = ('0' + (i + 1)).slice(-2);
    h += '<div class="gd-thumb" onclick="gdOpen(' + i + ')">' +
      '<img src="assets/guide/p' + n + '.jpg" alt="" loading="lazy"><div class="gd-cap">' + cap + '</div></div>';
  });
